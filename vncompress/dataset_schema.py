"""Shared contract for the VNCompress-VI v2 dataset.

One definition of the v2 schema, imported by both the builder and the
validator. If the two ever disagreed about what a valid row looks like, the
validator would certify exactly the thing it is meant to catch.

See docs/dataset_rebuild_spec.md.
"""
from __future__ import annotations

# S1 (docs/dataset_rebuild_spec.md SS5): `domain` is a small controlled task
# vocabulary. v1 used Wikidata instance-of values -- 429 of them, including
# "người" and "đơn vị phân loại" -- which inflated apparent domain diversity
# without describing the task at all. The Wikidata label, when kept, lives in
# `wikidata_type`.
CONTROLLED_DOMAINS = (
    'news', 'legal', 'medical', 'education', 'science',
    'history', 'admin', 'other',
)

# P5: "long_document_qa" in v1 had a median context of ~480 characters. A row
# is only long-document if it actually is.
LONG_DOCUMENT_MIN_TOKENS = 4000

# B1/SS2.2: budget compliance is measured against the REALIZED output, never
# against the ratio that was requested.
BUDGET_TOLERANCE = 0.15

# SS7 acceptance thresholds.
MIN_BUDGET_COMPLIANCE_RATE = 0.95
MAX_EMPTY_COLUMN_RATE = 0.50
MIN_INDEPENDENT_TEST_SAMPLES = 300

# SS6 E1 says "at least 300 samples, separated by document". Counting only the
# samples let a 1,000-row test set stand on 14 articles, four of which supplied
# 534 rows. Rows from one document are not independent draws, so the row floor
# needs a document floor beside it or it measures the wrong thing.
#
# 150 documents at <= 10 rows each reaches 1,000+ rows while keeping any single
# article's influence under a percent. Both numbers are floors on DIVERSITY,
# not on size, which is why they are separate from MIN_INDEPENDENT_TEST_SAMPLES.
MIN_EVAL_DOCUMENTS = 150
MAX_EVAL_DOC_SHARE = 0.05

# SS3.1: a gold compression is text SELECTED from the context. Every wave-2
# method selects -- perplexity over tokens, sentences, class budgets, encoder
# keep/drop labels -- so a gold containing sentences the context does not is a
# target none of them can reach.
#
# 0.80 rather than 1.00: joining two extracted clauses, or trimming a
# subordinate one, is legitimate compression and breaks verbatim sentence
# matching. The first v2 run scored 0.30, which is not that.
MIN_SENTENCE_EXTRACTIVE = 0.80

# --- Eval verification (SS6 E1/E2) ------------------------------------------
#
# The spec says the independent test set is verified by a PERSON. Verifying
# 1,000 rows by hand is not the constraint that has to be accepted, but neither
# is "an LLM said yes" the same claim -- so the two are recorded separately and
# never collapsed.
#
# What makes an LLM judge admissible HERE specifically: the eval
# `gold_compression` is cut from the human-marked ViQuAD answer span, not
# generated by a model. The judge is screening someone else's labels, not
# grading its own work. That is the whole difference from v1, where the test
# set WAS teacher output (P3/P4).
#
# What it does not make admissible: reporting the result as human verification.
# Hence `verification_method`, and a validator that refuses to read 'llm' as
# 'human'.

VERIFICATION_METHODS = ('none', 'llm', 'human', 'llm+human')

# A human sample large enough to put a usable confidence interval on the
# judge's agreement rate. At n=150 and ~90% agreement the 95% interval is
# roughly +/-5 points, which is tight enough to act on and small enough to
# review in a sitting.
MIN_HUMAN_VERIFIED_SAMPLES = 150

# Cohen's kappa, not raw agreement. When 90% of rows pass, a judge that says
# "pass" unconditionally scores 90% agreement and kappa 0 -- and only kappa
# tells the two apart.
MIN_JUDGE_AGREEMENT_KAPPA = 0.70

# The judge answers from the compression alone; this is how close it must come
# to the human answer to count as "still answerable".
ANSWERABLE_F1 = 0.60

# --- Per-config required fields (SS2) ---------------------------------------

CORPUS_FIELDS = (
    'id', 'doc_id', 'source', 'source_url', 'license', 'text',
    'char_length', 'token_count', 'text_lang', 'split',
)

COMPRESSION_FIELDS = (
    'id', 'doc_id', 'source', 'domain', 'split',
    'context', 'context_lang', 'query', 'query_lang',
    'gold_compression', 'requested_ratio',
    'target_tokens', 'realized_tokens', 'realized_ratio', 'budget_compliance',
    'extractive_ratio', 'numbers_preserved',
    # Token overlap alone reads 0.93 on a gold that quotes 30% of its
    # sentences; these two are what separate a compression from a rewrite.
    'sentence_extractive_ratio', 'unsupported_numbers',
    'answerable_from_compression',
    # Which of the acceptance routes admitted the row. Without it the gate's
    # own error rate cannot be audited after the fact.
    'answerability_method',
    'verification_method',
    'teacher', 'gen_config',
)

QA_FIELDS = (
    'id', 'doc_id', 'source', 'domain', 'split',
    'context', 'context_lang', 'query', 'question_type',
    'answer', 'answer_span', 'answer_lang', 'is_long_document',
)

CONFIG_FIELDS = {
    'corpus': CORPUS_FIELDS,
    'compression': COMPRESSION_FIELDS,
    'qa': QA_FIELDS,
}


def budget_compliant(realized_tokens, target_tokens, tolerance: float = BUDGET_TOLERANCE):
    """SS2.2: abs(realized - target) / target <= tolerance.

    Returns None when either side is missing -- an unmeasurable row is not a
    compliant one, and must not be silently counted as passing.
    """
    if not target_tokens or realized_tokens is None:
        return None
    return abs(realized_tokens - target_tokens) / target_tokens <= tolerance
